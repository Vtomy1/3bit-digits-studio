import { ExportFormat, ProcessedResult } from '../types';

export function generateExportContent(result: ProcessedResult, format: ExportFormat): string {
  const { digits, paletteIndices, width, height, palette } = result;

  switch (format) {
    case 'txt-raw': {
      return digits.map(row => row.join('')).join('\n');
    }

    case 'txt-spaced': {
      return digits.map(row => row.join(' ')).join('\n');
    }

    case 'csv': {
      return digits.map(row => row.join(',')).join('\n');
    }

    case 'txt-header': {
      const headerLines = [
        '# ============================================================',
        '# BitDigit Studio — 3-Bit Digit Matrix Export',
        `# Resolution: ${width} × ${height} (${width * height} digits)`,
        `# Palette: ${palette.name}`,
        '# Color Mapping:',
        ...palette.colors.map(
          c => `#   Digit ${c.digit} -> ${c.name} (${c.hex} | RGB: ${c.rgb.join(',')})`
        ),
        `# Exported: ${new Date().toISOString()}`,
        '# ============================================================',
        '',
      ];
      const dataLines = digits.map(row => row.join(''));
      return [...headerLines, ...dataLines].join('\n');
    }

    case 'code-c': {
      const rows = paletteIndices
        .map(row => `  { ${row.join(', ')} }`)
        .join(',\n');
      return `// Generated by BitDigit Studio
// Resolution: ${width}x${height}
// Palette: ${palette.name}
#include <stdint.h>

#define BITDIGIT_WIDTH ${width}
#define BITDIGIT_HEIGHT ${height}

const uint8_t image_digits[${height}][${width}] = {
${rows}
};
`;
    }

    case 'code-python': {
      const rows = paletteIndices
        .map(row => `    [${row.join(', ')}]`)
        .join(',\n');
      return `# Generated by BitDigit Studio
# Resolution: ${width}x${height}
# Palette: ${palette.name}

IMAGE_WIDTH = ${width}
IMAGE_HEIGHT = ${height}

IMAGE_DIGITS = [
${rows}
]
`;
    }

    case 'code-json': {
      return JSON.stringify(
        {
          width,
          height,
          palette: {
            id: palette.id,
            name: palette.name,
            colors: palette.colors.map(c => ({
              digit: c.digit,
              name: c.name,
              hex: c.hex,
              rgb: c.rgb,
            })),
          },
          digits: digits.map(row => row.join('')),
          matrix: paletteIndices,
        },
        null,
        2
      );
    }

    case 'ansi-terminal': {
      // ANSI 8-color foreground escape codes
      // Standard ANSI color codes: 30=Black, 34=Blue, 32=Green, 36=Cyan, 31=Red, 35=Magenta, 33=Yellow, 37=White
      // For general 3-bit RGB we can map each color or use truecolor ANSI \x1b[38;2;R;G;Bm
      const lines = digits.map((row, y) => {
        return row
          .map((char, x) => {
            const color = result.pixelColors[y][x];
            return `\x1b[38;2;${color.r};${color.g};${color.b}m${char}\x1b[0m`;
          })
          .join('');
      });
      return lines.join('\n');
    }

    default:
      return digits.map(row => row.join('')).join('\n');
  }
}

export function downloadFile(content: string, filename: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
    // Fallback for environments where clipboard API is restricted
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    const success = document.execCommand('copy');
    document.body.removeChild(textarea);
    return success;
  } catch (err) {
    console.error('Failed to copy to clipboard', err);
    return false;
  }
}

export function downloadDitheredImagePng(result: ProcessedResult, scale = 8, filename = 'dithered-image.png') {
  const canvas = document.createElement('canvas');
  canvas.width = result.width * scale;
  canvas.height = result.height * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  ctx.imageSmoothingEnabled = false;

  for (let y = 0; y < result.height; y++) {
    for (let x = 0; x < result.width; x++) {
      const color = result.pixelColors[y][x];
      ctx.fillStyle = `rgb(${color.r}, ${color.g}, ${color.b})`;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }

  canvas.toBlob(blob => {
    if (!blob) return;
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
  }, 'image/png');
}
